-- CollectWise schema for Supabase (Postgres).
-- Ported from the Oracle APEX workspace WKSP_COLLECTION: table and column names are kept.
-- CW_REPORTS is merged into cw_missed_reports (keeps its categories, adds resolution time).
-- Not ported: live GPS tracking, collector visits and photos, registration requests,
-- survey responses (Google Form) and the APEX login functions.

create table cw_roles (
  role_id   integer generated by default as identity primary key,
  role_code text not null unique
            check (role_code in ('RESIDENT', 'COLLECTOR', 'MANAGEMENT', 'ADMIN')),
  role_name text not null
);

create table cw_floors (
  floor_id     integer generated by default as identity primary key,
  block_name   text    not null default 'Block 2',
  floor_number integer not null,
  floor_label  text    not null,
  is_active    boolean not null default true,
  unique (block_name, floor_number)
);

create table cw_users (
  user_id        integer generated by default as identity primary key,
  apex_username  text unique,
  full_name      text not null,
  email          text,
  phone_number   text unique,
  role_id        integer not null default 1 references cw_roles (role_id),
  floor_id       integer references cw_floors (floor_id),
  account_status text not null default 'ACTIVE'
                 check (account_status in ('PENDING', 'ACTIVE', 'INACTIVE')),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz
);

create table cw_collection_schedules (
  schedule_id     integer generated by default as identity primary key,
  floor_id        integer not null references cw_floors (floor_id),
  collection_date date    not null,
  start_time      timestamptz not null,
  end_time        timestamptz,
  schedule_status text not null default 'SCHEDULED'
                  check (schedule_status in ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
  created_by      integer references cw_users (user_id),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz,
  notes           text,
  check (end_time is null or end_time >= start_time)
);

create table cw_collection_logs (
  log_id              integer generated by default as identity primary key,
  schedule_id         integer not null unique references cw_collection_schedules (schedule_id),
  collector_id        integer not null references cw_users (user_id),
  checkin_time        timestamptz not null default now(),
  client_checkin_time timestamptz,
  synced_at           timestamptz,
  sync_status         text not null default 'SYNCED' check (sync_status in ('PENDING', 'SYNCED')),
  collection_status   text not null default 'COMPLETED'
                      check (collection_status in ('COMPLETED', 'NEEDS_FOLLOW_UP')),
  remarks             text
);

create table cw_missed_reports (
  report_id        integer generated by default as identity primary key,
  resident_id      integer not null references cw_users (user_id),
  floor_id         integer references cw_floors (floor_id),
  schedule_id      integer references cw_collection_schedules (schedule_id),
  report_category  text not null default 'Uncollected Garbage'
                   check (report_category in ('Uncollected Garbage', 'Overflowing Bin',
                          'Illegal Dumping', 'Damaged Bin', 'Other')),
  description      text,
  report_status    text not null default 'PENDING'
                   check (report_status in ('PENDING', 'IN_PROGRESS', 'RESOLVED', 'REJECTED')),
  reported_at      timestamptz not null default now(),
  assigned_to      integer references cw_users (user_id),
  resolved_at      timestamptz,
  resolution_notes text,
  sms_id           text unique  -- textbee smsId when the report came from an SMS reply
);

create table cw_notification_logs (
  notification_id   integer generated by default as identity primary key,
  user_id           integer not null references cw_users (user_id),
  schedule_id       integer references cw_collection_schedules (schedule_id),
  notification_type text not null default 'COLLECTION_REMINDER',
  message_text      text not null,
  recipient_phone   text,
  sent_at           timestamptz,
  delivery_status   text not null default 'QUEUED'
                    check (delivery_status in ('QUEUED', 'SENT', 'DELIVERED', 'FAILED')),
  provider_ref      text,
  error_message     text,
  created_at        timestamptz not null default now()
);

create index on cw_users (floor_id);
create index on cw_collection_schedules (collection_date, floor_id);
create index on cw_missed_reports (report_status);
create index on cw_notification_logs (schedule_id);

-- "Today" is Malaysian time; Supabase runs in UTC.
create view cw_v_dashboard_summary
with (security_invoker = true) as
select
  (select count(*) from cw_collection_schedules
    where collection_date = (now() at time zone 'Asia/Kuala_Lumpur')::date
      and schedule_status <> 'CANCELLED') as scheduled_today,
  (select count(*) from cw_collection_logs l
     join cw_collection_schedules s on s.schedule_id = l.schedule_id
    where s.collection_date = (now() at time zone 'Asia/Kuala_Lumpur')::date
      and l.collection_status = 'COMPLETED') as completed_today,
  (select count(*) from cw_missed_reports
    where report_status in ('PENDING', 'IN_PROGRESS')) as open_reports,
  (select count(*) from cw_users
    where account_status = 'ACTIVE') as active_users;

create view cw_v_floor_progress
with (security_invoker = true) as
select s.schedule_id, s.collection_date, s.start_time, s.schedule_status,
       f.floor_id, f.block_name, f.floor_number, f.floor_label,
       l.log_id, l.checkin_time, l.collection_status,
       case when l.log_id is not null then 'COMPLETED'
            when s.schedule_status = 'CANCELLED' then 'CANCELLED'
            else 'PENDING' end as progress_status
from cw_collection_schedules s
join cw_floors f on f.floor_id = s.floor_id
left join cw_collection_logs l on l.schedule_id = s.schedule_id;

-- Collector identity is passed in by the app's server code instead of APEX's APP_USER.
create function cw_collector_checkin(
  p_schedule_id  integer,
  p_collector_id integer,
  p_remarks      text default null
) returns integer
language plpgsql as $$
declare
  v_status text;
  v_log_id integer;
begin
  if not exists (
    select 1 from cw_users u join cw_roles r on r.role_id = u.role_id
     where u.user_id = p_collector_id and r.role_code = 'COLLECTOR'
       and u.account_status = 'ACTIVE'
  ) then
    raise exception 'Only active collectors can check in.';
  end if;

  select schedule_status into v_status
    from cw_collection_schedules
   where schedule_id = p_schedule_id
     for update;

  if v_status is distinct from 'SCHEDULED' then
    raise exception 'This schedule is not open for check-in.';
  end if;

  insert into cw_collection_logs
    (schedule_id, collector_id, client_checkin_time, synced_at, remarks)
  values
    (p_schedule_id, p_collector_id, now(), now(), p_remarks)
  returning log_id into v_log_id;

  update cw_collection_schedules
     set schedule_status = 'COMPLETED', updated_at = now()
   where schedule_id = p_schedule_id;

  return v_log_id;
exception
  when unique_violation then
    raise exception 'This floor collection has already been checked in.';
end;
$$;

create function cw_update_report_status(
  p_report_id  integer,
  p_new_status text,
  p_user_id    integer,
  p_notes      text default null
) returns void
language plpgsql as $$
begin
  update cw_missed_reports
     set report_status    = p_new_status,
         resolution_notes = p_notes,
         resolved_at      = case when p_new_status = 'RESOLVED' then now() end,
         assigned_to      = p_user_id
   where report_id = p_report_id;

  if not found then
    raise exception 'Report not found.';
  end if;
end;
$$;

-- Only the app's server (service role key) reads or writes; no public access.
alter table cw_roles                enable row level security;
alter table cw_floors               enable row level security;
alter table cw_users                enable row level security;
alter table cw_collection_schedules enable row level security;
alter table cw_collection_logs      enable row level security;
alter table cw_missed_reports       enable row level security;
alter table cw_notification_logs    enable row level security;

revoke execute on function cw_collector_checkin(integer, integer, text) from public, anon, authenticated;
revoke execute on function cw_update_report_status(integer, text, integer, text) from public, anon, authenticated;
